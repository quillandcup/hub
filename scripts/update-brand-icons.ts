import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

/**
 * `pnpm brand-icons:update`: regenerates `src/components/landing/brand-icons.generated.ts`, the real marks of the social networks
 * (docs/product/LANDING_PAGES.md, "Social icons"). The marks come from the `simple-icons` package (CC0-1.0, public domain), pinned to
 * ONE version below. Nothing is added to package.json or the lockfile and nothing is installed into the repo: the tarball is
 * downloaded with `npm pack` into a temporary directory, checked against the integrity the npm registry publishes, read, and removed.
 *
 * To refresh: change `VERSION` (and, to offer another network, `WANTED`), run `pnpm brand-icons:update`, review the diff, commit.
 * The script writes nothing and exits non-zero if the download or its integrity fails or a wanted network is missing from that version
 * (LinkedIn is not in simple-icons: its mark is hand-drawn in `brand-icons.drawn.ts`). Never edit the generated file by hand.
 */
export const VERSION = "16.38.1";
/** The networks to copy: our key, then simple-icons' slug. */
export const WANTED: Record<string, string> = {
  instagram: "instagram",
  facebook: "facebook",
  youtube: "youtube",
  tiktok: "tiktok",
  pinterest: "pinterest",
  substack: "substack",
  x: "x",
  threads: "threads",
};
const OUTPUT = "src/components/landing/brand-icons.generated.ts";

type Entry = { slug: string; title: string; hex: string; path: string };

/** The `d` of the one `<path>` of an icon's SVG; throws on anything else, so no markup ever reaches the generated file. */
export function pathOf(svg: string): string {
  const paths = [...svg.matchAll(/<path\s+d="([^"]+)"\s*\/>/g)];
  if (paths.length !== 1) throw new Error(`expected exactly one <path d="..."/>, found ${paths.length}`);
  const d = paths[0][1];
  if (!/^[MmLlHhVvCcSsQqTtAaZz0-9eE.,\s-]+$/.test(d)) throw new Error("the path holds something other than path commands and numbers");
  return d;
}

export function render(entries: Record<string, Entry>): string {
  const body = Object.entries(entries)
    .map(([key, e]) => `  ${key}: { slug: ${JSON.stringify(e.slug)}, title: ${JSON.stringify(e.title)}, hex: ${JSON.stringify(e.hex)}, path: ${JSON.stringify(e.path)} },`)
    .join("\n");
  return `/**
 * GENERATED by scripts/update-brand-icons.ts (\`pnpm brand-icons:update\`). Do not edit by hand.
 * Source: the \`simple-icons\` package, version ${VERSION}, license CC0-1.0 (public domain), https://simpleicons.org.
 * Each entry is a network's own mark as one SVG path on a 24 x 24 grid, with its official colour. The marks are used as they are:
 * not redrawn, distorted or recoloured (docs/product/LANDING_PAGES.md, "Social icons"; the marks stay listed in CUSTOM_DRAWINGS in tests/lib/icons.test.ts).
 * The networks simple-icons does not have (LinkedIn) are drawn by hand in brand-icons.drawn.ts.
 */
export type BrandIcon = { slug: string; title: string; hex: string; path: string };

export const BRAND_ICONS = {
${body}
} as const satisfies Record<string, BrandIcon>;
`;
}

export type Run = (cmd: string, args: string[], cwd: string) => string;

export const run: Run = (cmd, args, cwd) => {
  const r = spawnSync(cmd, args, { cwd, encoding: "utf8" });
  if (r.status !== 0) throw new Error(`${cmd} ${args.join(" ")} failed: ${r.stderr || r.stdout}`);
  return r.stdout.trim();
};

/** Downloads (through `runner`) simple-icons@VERSION into `dir`, checks it, and returns the generated module's text. Throws, so nothing is written, on any failure. */
export function generate(dir: string, runner: Run): string {
  const expected = runner("npm", ["view", `simple-icons@${VERSION}`, "dist.integrity"], dir);
  if (!expected.startsWith("sha512-")) throw new Error(`no sha512 integrity published for simple-icons@${VERSION}`);
  const file = runner("npm", ["pack", `simple-icons@${VERSION}`, "--silent"], dir).split("\n").pop()!;
  const actual = `sha512-${createHash("sha512").update(readFileSync(path.join(dir, file))).digest("base64")}`;
  if (actual !== expected) throw new Error(`integrity mismatch for ${file}: the registry says ${expected}, the download is ${actual}`);
  runner("tar", ["-xzf", file], dir);
  const pkg = JSON.parse(readFileSync(path.join(dir, "package", "package.json"), "utf8")) as { version: string; license: string };
  if (pkg.version !== VERSION || pkg.license !== "CC0-1.0") throw new Error(`unexpected package: ${pkg.version} under ${pkg.license}`);
  const data = JSON.parse(readFileSync(path.join(dir, "package", "data", "simple-icons.json"), "utf8")) as { title: string; slug?: string; hex: string }[];

  const entries: Record<string, Entry> = {};
  const missing: string[] = [];
  for (const [key, slug] of Object.entries(WANTED)) {
    const meta = data.find((i) => i.slug === slug);
    if (!meta || !/^[0-9A-Fa-f]{6}$/.test(meta.hex)) {
      missing.push(key);
      continue;
    }
    entries[key] = { slug, title: meta.title, hex: meta.hex.toUpperCase(), path: pathOf(readFileSync(path.join(dir, "package", "icons", `${slug}.svg`), "utf8")) };
  }
  if (missing.length > 0) throw new Error(`not in simple-icons@${VERSION}: ${missing.join(", ")}. Nothing was written.`);
  return render(entries);
}

export function main(runner: Run = run, output: string = OUTPUT) {
  const dir = mkdtempSync(path.join(tmpdir(), "simple-icons-"));
  try {
    writeFileSync(output, generate(dir, runner));
    console.log(`Wrote ${output} from simple-icons@${VERSION} (integrity checked).`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

// Run only when started as a script, so the helpers can be tested.
if (process.argv[1] && path.resolve(process.argv[1]).endsWith("update-brand-icons.ts")) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
