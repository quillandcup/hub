/**
 * The demo's own local Supabase stack, separate from the shared dev one: another project id, ports
 * shifted by 2000 (API 56321, DB 56322, mail 56324) and the app on 3100, so it can run beside the dev stack
 * and is always built from this branch's migrations.
 *
 *   pnpm demo:stack up     start it (applies every migration, no seed.sql) and write demo/.env.demo
 *   pnpm demo:stack migrate apply migrations added since `up` (after pulling, or adding one)
 *   pnpm demo:stack down   stop it (data is kept in its Docker volumes)
 *   pnpm demo:stack reset  stop it and delete its data, so the next `up` starts from migrations
 *
 * The config is generated from supabase/config.toml so it can't drift from it. See docs/DEMO_AND_HELP.md.
 */
import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Another worktree's stack is another project id and another set of ports: `supabase stop` goes by project id, so two
// worktrees on the default would stop each other's containers. DEMO_STACK_ID=<name> DEMO_PORT_SHIFT=<n> (default
// 2000, so the app is on 3100 + (n - 2000)) gives this one its own; see docs/DEMO_AND_HELP.md.
export const DEMO_PROJECT_ID = process.env.DEMO_STACK_ID ?? "hub-demo";
const PORT_SHIFT = Number(process.env.DEMO_PORT_SHIFT ?? 2000);
export const DEMO_APP_PORT = 3100 + (PORT_SHIFT - 2000);
// Services the dev stack also skips; none is needed to run the app.
const EXCLUDED = ["imgproxy", "edge-runtime", "studio", "logflare", "vector"];

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const workdir = path.join(root, "demo", ".stack");
const envFile = path.join(root, "demo", ".env.demo");

/** The dev config with a different project id, shifted ports, the app on 3100, and no production overrides. */
export function demoConfig(devConfig: string): string {
  const beforeRemotes = devConfig.split(/^\[remotes\./m)[0];
  return beforeRemotes
    .replace(/^project_id = ".*"$/m, `project_id = "${DEMO_PROJECT_ID}"`)
    .replace(/^(\s*#?\s*\w*port = )(543\d\d)$/gm, (_m, head: string, port: string) => `${head}${Number(port) + PORT_SHIFT}`)
    .replace(/localhost:3000/g, `localhost:${DEMO_APP_PORT}`)
    .replace(/127\.0\.0\.1:3000/g, `127.0.0.1:${DEMO_APP_PORT}`)
    .replace(/(\[db\.seed\]\s*\n(?:#.*\n)*enabled = )true/, "$1false");
}

/** A fresh copy each time: the CLI rejects symlinks that point outside the project, and a copy follows deleted files. */
function copyFromDev(name: string) {
  const dest = path.join(workdir, "supabase", name);
  rmSync(dest, { recursive: true, force: true });
  cpSync(path.join(root, "supabase", name), dest, { recursive: true });
}

function supabase(...args: string[]): string {
  return execFileSync("supabase", [...args, "--workdir", workdir], { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] });
}

function prepare() {
  mkdirSync(path.join(workdir, "supabase"), { recursive: true });
  const devConfig = readFileSync(path.join(root, "supabase", "config.toml"), "utf8");
  writeFileSync(path.join(workdir, "supabase", "config.toml"), demoConfig(devConfig));
  for (const name of ["migrations", "templates", "emails"]) copyFromDev(name);
}

function writeEnv() {
  const status = JSON.parse(supabase("status", "-o", "json")) as Record<string, string>;
  const lines = [
    `# Generated by demo/stack.ts. The demo stack's local URL and the standard local development keys.`,
    `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${status.ANON_KEY}`,
    `SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}`,
    `DEMO_MAIL_URL=${status.MAILPIT_URL}`,
    ``,
  ];
  writeFileSync(envFile, lines.join("\n"));
  console.log(`Wrote ${path.relative(root, envFile)}; API at ${status.API_URL}`);
}

function main(command: string | undefined) {
  if (command === "up") {
    prepare();
    execFileSync("supabase", ["start", "--workdir", workdir, ...EXCLUDED.flatMap((s) => ["-x", s])], { stdio: "inherit" });
    writeEnv();
  } else if (command === "migrate") {
    prepare();
    execFileSync("supabase", ["migration", "up", "--local", "--workdir", workdir], { stdio: "inherit" });
  } else if (command === "down") {
    prepare();
    execFileSync("supabase", ["stop", "--workdir", workdir], { stdio: "inherit" });
  } else if (command === "reset") {
    prepare();
    execFileSync("supabase", ["stop", "--workdir", workdir, "--no-backup"], { stdio: "inherit" });
    rmSync(envFile, { force: true });
  } else {
    console.error("Usage: pnpm demo:stack up|migrate|down|reset");
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv[2]);
