import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { VERSION, WANTED, generate, main, run, type Run } from "@/scripts/update-brand-icons";

const dirs: string[] = [];
const tmp = () => {
  const d = mkdtempSync(path.join(tmpdir(), "brand-icons-test-"));
  dirs.push(d);
  return d;
};
afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
});

const TARBALL = "simple-icons-test.tgz";
const BYTES = "pretend tarball";
const integrity = (bytes: string) => `sha512-${createHash("sha512").update(bytes).digest("base64")}`;

/** A stand-in for npm and tar: "downloads" a tarball and "extracts" a package with the icons of `slugs`, under `license`. Made-up marks only. */
function fakeRun(opts: { published?: string; license?: string; slugs?: string[]; svg?: (slug: string) => string } = {}): Run & { calls: string[] } {
  const slugs = opts.slugs ?? Object.values(WANTED);
  const calls: string[] = [];
  const fn = ((cmd: string, args: string[], cwd: string) => {
    calls.push(`${cmd} ${args[0]}`);
    if (cmd === "npm" && args[0] === "view") return opts.published ?? integrity(BYTES);
    if (cmd === "npm" && args[0] === "pack") {
      writeFileSync(path.join(cwd, TARBALL), BYTES);
      return `npm notice\n${TARBALL}`;
    }
    mkdirSync(path.join(cwd, "package", "icons"), { recursive: true });
    mkdirSync(path.join(cwd, "package", "data"), { recursive: true });
    writeFileSync(path.join(cwd, "package", "package.json"), JSON.stringify({ version: VERSION, license: opts.license ?? "CC0-1.0" }));
    writeFileSync(path.join(cwd, "package", "data", "simple-icons.json"), JSON.stringify(slugs.map((slug) => ({ title: slug.toUpperCase(), slug, hex: "0a1b2c" }))));
    for (const slug of slugs) writeFileSync(path.join(cwd, "package", "icons", `${slug}.svg`), opts.svg?.(slug) ?? `<svg role="img" viewBox="0 0 24 24"><title>${slug}</title><path d="M1 1h${slug.length}v2z"/></svg>`);
    return "";
  }) as Run & { calls: string[] };
  fn.calls = calls;
  return fn;
}

describe("update-brand-icons", () => {
  it("turns the pinned package into a module with an entry per wanted network, colours in capitals", () => {
    const runner = fakeRun();
    const out = generate(tmp(), runner);
    expect(runner.calls).toEqual(["npm view", "npm pack", "tar -xzf"]);
    for (const key of Object.keys(WANTED)) expect(out).toContain(`${key}: { slug: "${WANTED[key]}", title: "${WANTED[key].toUpperCase()}", hex: "0A1B2C", path: "M1 1h`);
    expect(out).toContain(`version ${VERSION}`);
  });

  it("refuses a download whose integrity is not the one the registry publishes", () => {
    expect(() => generate(tmp(), fakeRun({ published: integrity("something else") }))).toThrow(/integrity mismatch/);
    expect(() => generate(tmp(), fakeRun({ published: "" }))).toThrow(/no sha512 integrity/);
  });

  it("refuses a package of another license", () => {
    expect(() => generate(tmp(), fakeRun({ license: "MIT" }))).toThrow(/unexpected package/);
  });

  it("names the networks the package lacks and produces nothing", () => {
    expect(() => generate(tmp(), fakeRun({ slugs: ["instagram"] }))).toThrow(/not in simple-icons.*facebook/);
  });

  it("refuses an icon that is not one plain path", () => {
    expect(() => generate(tmp(), fakeRun({ svg: () => '<svg><path d="M1 1"/><rect/></svg><path d="M2 2"/>' }))).toThrow(/exactly one/);
  });

  it("writes the module to the output path and cleans up its temporary folder", () => {
    const out = path.join(tmp(), "out.ts");
    main(fakeRun(), out);
    expect(readFileSync(out, "utf8")).toContain("GENERATED by scripts/update-brand-icons.ts");
  });

  it("writes nothing when it fails", () => {
    const out = path.join(tmp(), "out.ts");
    expect(() => main(fakeRun({ slugs: [] }), out)).toThrow();
    expect(existsSync(out)).toBe(false);
  });

  it("runs a command and reports its output, or why it failed", () => {
    expect(run("node", ["-e", "console.log('hi')"], tmpdir())).toBe("hi");
    expect(() => run("node", ["-e", "process.exit(3)"], tmpdir())).toThrow(/failed/);
  });
});
