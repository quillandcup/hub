// @vitest-environment jsdom
/** The social marks: the networks' real marks (generated from simple-icons, `scripts/update-brand-icons.ts`) and the few drawn by hand. */
import { describe, expect, it } from "vitest";
import { render, screen, within } from "@testing-library/react";
import { BRAND_ICONS } from "@/components/landing/brand-icons.generated";
import { DRAWN_MARKS } from "@/components/landing/brand-icons.drawn";
import { SiteFooterView, SiteHeaderView } from "@/components/landing/site-frame";
import { BLACK_ON_BADGE, MIN_GRAPHIC_CONTRAST, SocialMark, brandHex, contrast, markHex } from "@/components/landing/social-marks";
import { SOCIAL_NETWORKS } from "@/components/landing/social-networks";
import { SOCIAL_NETWORKS as SITE_NETWORKS, normalizeSiteTemplate } from "@/lib/landing/site-template";
import { VERSION, WANTED, pathOf, render as renderModule } from "@/scripts/update-brand-icons";

const networks = Object.keys(SOCIAL_NETWORKS) as (keyof typeof SOCIAL_NETWORKS)[];
const all = { ...BRAND_ICONS, ...DRAWN_MARKS } as Record<string, { title: string; hex: string; path: string }>;

describe("the brand marks", () => {
  it("has a mark, an official colour and a name for every network the block and the site template offer", () => {
    for (const n of [...networks, ...SITE_NETWORKS.map((s) => s.value)]) {
      expect(all[n], n).toBeDefined();
      expect(all[n].hex, n).toMatch(/^[0-9A-F]{6}$/);
      expect(all[n].title, n).toBe(SOCIAL_NETWORKS[n as keyof typeof SOCIAL_NETWORKS]);
      expect(all[n].path.length, n).toBeGreaterThan(20);
    }
    for (const s of SITE_NETWORKS) expect(s.label).toBe(SOCIAL_NETWORKS[s.value]);
  });

  it("holds only plain SVG path data: commands and numbers, no markup", () => {
    for (const [n, m] of Object.entries(all)) expect(m.path, n).toMatch(/^[MmLlHhVvCcSsQqTtAaZz0-9eE.,\s-]+$/);
  });

  it("generates the networks simple-icons has, and draws the ones it does not (LinkedIn, Email, Website) in a separate file", () => {
    expect(Object.keys(BRAND_ICONS).sort()).toEqual(Object.keys(WANTED).sort());
    expect(Object.keys(DRAWN_MARKS).sort()).toEqual(["email", "linkedin", "website"]);
    for (const [key, icon] of Object.entries(BRAND_ICONS)) expect(icon.slug, key).toBe(WANTED[key]);
    expect(VERSION).toMatch(/^\d+\.\d+\.\d+$/);
  });

  it("draws every mark in a colour with enough contrast (3:1) on the white badge, and in the black version where its own is too faint", () => {
    for (const n of networks) expect(contrast(markHex(n), "FFFFFF"), n).toBeGreaterThanOrEqual(MIN_GRAPHIC_CONTRAST);
    expect(BLACK_ON_BADGE).toEqual(["substack"]);
    expect(markHex("substack")).toBe("000000");
    expect(markHex("instagram")).toBe(brandHex("instagram"));
    expect(markHex("youtube", "dark")).toBe("000000");
    expect(markHex("youtube", "light")).toBe("FFFFFF");
    expect(contrast("000000", "FFFFFF")).toBeCloseTo(21, 0);
  });

  it("draws a mark hidden from screen readers, in its colour, from one path", () => {
    const { container } = render(<SocialMark network="pinterest" />);
    const svg = container.querySelector("svg")!;
    expect(svg).toHaveAttribute("aria-hidden", "true");
    expect(svg).toHaveAttribute("viewBox", "0 0 24 24");
    expect(svg).toHaveStyle({ color: `#${BRAND_ICONS.pinterest.hex}` });
    expect(svg.querySelectorAll("path")).toHaveLength(1);
    expect(svg.querySelector("path")!.getAttribute("d")).toBe(BRAND_ICONS.pinterest.path);
    expect(render(<SocialMark network="email" />).container.querySelector("svg")).toHaveAttribute("stroke", "currentColor");
  });
});

describe("the update script", () => {
  it("accepts a single plain path and refuses markup or several paths", () => {
    expect(pathOf('<svg><title>X</title><path d="M1 1h2v2z"/></svg>')).toBe("M1 1h2v2z");
    expect(() => pathOf('<svg><path d="M1 1"/><path d="M2 2"/></svg>')).toThrow();
    expect(() => pathOf('<svg><path d="M1 1<script>"/></svg>')).toThrow();
  });

  it("writes a header that says where the marks come from and not to edit it by hand", () => {
    const out = renderModule({ x: { slug: "x", title: "X", hex: "000000", path: "M1 1z" } });
    for (const part of ["GENERATED by scripts/update-brand-icons.ts", "pnpm brand-icons:update", "Do not edit by hand", `version ${VERSION}`, "CC0-1.0"]) expect(out).toContain(part);
    expect(out).toContain('x: { slug: "x", title: "X", hex: "000000", path: "M1 1z" }');
  });
});

describe("the site footer and header social links, by look", () => {
  const social = [{ network: "x", href: "https://example.test/x" }, { network: "substack", href: "https://example.test/s" }];
  const footer = (socialLook?: string) => normalizeSiteTemplate({ footer: { show: true, text: "", links: [], social, socialLook } }).footer;

  it("is the colour marks on a light badge by default, for a template saved before the choice too", () => {
    const { container } = render(<>{SiteFooterView({ footer: footer() })}</>);
    const list = screen.getByRole("list", { name: "Social links" });
    expect(list.className).not.toContain("!text-");
    const link = within(list).getByRole("link", { name: "X" });
    expect(link.className).toContain("bg-white");
    expect(link.className).toContain("border-neutral-300");
    expect(container.querySelector('svg[data-network="x"]')).toHaveStyle({ color: "#000000" });
    expect(container.querySelector('svg[data-network="substack"]')).toHaveStyle({ color: "#000000" });
  });

  it("can be the black or the white marks with no badge, in the footer and in the header's social block", () => {
    for (const [look, mark] of [["dark", "!text-black"], ["light", "!text-white"]] as const) {
      const f = render(<>{SiteFooterView({ footer: footer(look) })}</>);
      expect(screen.getByRole("list", { name: "Social links" }).className).toContain(mark);
      expect(screen.getByRole("list", { name: "Social links" }).className).toContain("[&_.lp-social]:!bg-transparent");
      f.unmount();
      const header = normalizeSiteTemplate({ header: { show: true, items: [{ id: "o", type: "social", links: social, look }] } }).header;
      const h = render(<>{SiteHeaderView({ header })}</>);
      expect(screen.getByRole("list", { name: "Social links" }).className).toContain(mark);
      expect(screen.getByRole("link", { name: "X" })).toBeInTheDocument();
      h.unmount();
    }
  });
});
