import { DISPOSABLE_EMAIL_DOMAINS } from "@/lib/disposable-email-domains.generated";

/**
 * Temporary-mail addresses (throwaway inboxes) are refused where a visitor or member gives us an email on their
 * own: the landing-page opt-in form and "add an email alias" in settings. Sign-in is invite-only and imports come
 * from Kajabi, so they don't need it.
 *
 * The list is the public CC0 blocklist (disposable-email-domains/disposable-email-domains), committed as
 * `disposable-email-domains.generated.ts` and refreshed with `pnpm disposable-domains:update`.
 */

export const DISPOSABLE_EMAIL_MESSAGE = "Please use your own email address, not a temporary one.";

const BLOCKED = new Set<string>(DISPOSABLE_EMAIL_DOMAINS);

/** Domains from the blocklist file: one per line, `#` comments and blanks ignored, lowercased, de-duplicated, sorted. */
export function parseBlocklist(text: string): string[] {
  const domains = text
    .split(/\r?\n/)
    .map((line) => line.replace(/#.*/, "").trim().toLowerCase())
    .filter(Boolean);
  return [...new Set(domains)].sort();
}

export function renderDomainsModule(domains: string[], source: string, date: string): string {
  return `// Generated by scripts/update-disposable-email-domains.ts on ${date} from ${source} (CC0). Do not edit by hand.\nexport const DISPOSABLE_EMAIL_DOMAINS: readonly string[] = ${JSON.stringify(domains)};\n`;
}

/** True when the address's domain, or a parent of it (`x.mailinator.com`), is on the blocklist. */
export function isDisposableEmail(email: string): boolean {
  const at = email.lastIndexOf("@");
  if (at < 0) return false;
  const labels = email
    .slice(at + 1)
    .trim()
    .toLowerCase()
    .replace(/\.$/, "")
    .split(".");
  for (let i = 0; i < labels.length - 1; i++) {
    if (BLOCKED.has(labels.slice(i).join("."))) return true;
  }
  return false;
}
